"""
UNKNOWN X – Document Overview Service (Task P1-4)

Generates a rich document overview on first open or upload; caches by file hash so every
subsequent open makes zero LLM calls.

Overview fields:
  title, authors, year, page_count, language, summary (up to 5 grounded sentences with
  page refs), key_topics, figure/table count with thumbnails, Document IQ,
  5 suggested questions (each labelled grounded or exploratory), and a per-section status.

The summary is produced via the existing grounded-generation path:
  grounded_generate() → verify_and_filter_sentences()
Each verified sentence carries source_ids that map to the passage page number.

Milestone 1 integrity rules:
  Step 1
  * Figures and tables are reported ONLY when a real caption line ("Figure N: ...",
    "Table N. ...") is found in the extracted page text. No caption -> not counted.
  * A summary sentence only carries a page reference that comes from a retrieved
    passage's own page metadata. If no real page exists, the sentence is dropped.
  * Cached overviews written by an older schema version are ignored and regenerated.
  Step 2
  * Every section reports its own status (ok / partial / empty / unavailable / failed),
    with an error message when something failed. One failing section never erases the others.
  * Suggested questions carry provenance: "grounded" (generated by the LLM from retrieved
    document passages) or "exploratory" (generic template, NOT derived from the document).
  * Missing metadata (title, authors, year) is disclosed, never invented.
  * An overview is not cached when retrieval, Document IQ or figure/table detection failed,
    so a transient infrastructure failure is retried on the next request instead of being frozen.
"""

from __future__ import annotations

import json
import re
import time
import urllib.parse
from pathlib import Path
from typing import Any

from app.rag.config import settings
from app.rag.grounded_generation import build_grounded_prompt, verify_and_filter_sentences
from app.rag.logger import logger

OVERVIEW_CACHE_DIR = settings.CACHE_DIR / "overviews"
OVERVIEW_CACHE_DIR.mkdir(parents=True, exist_ok=True)

# Bump whenever the overview contract changes so stale cache entries are regenerated.
# v1 (implicit, no field): fabricated figures/tables and positional page refs.
# v2: caption-based figures/tables, honest page refs.
# v3: adds question_details and section_status.
OVERVIEW_SCHEMA_VERSION = 4

# Sections whose failure means the overview should not be cached.
_NON_CACHEABLE_FAILURES = ("retrieval", "document_iq", "figures_tables")


def _section(status: str, error: str | None = None, **detail: Any) -> dict[str, Any]:
    """Build one section-status entry. status: ok | partial | empty | unavailable | failed."""
    return {"status": status, "error": error, "detail": detail}


def _err(exc: Exception) -> str:
    return f"{type(exc).__name__}: {exc}"


# ---------------------------------------------------------------------------
# Cache helpers
# ---------------------------------------------------------------------------

def _cache_path(doc_hash: str) -> Path:
    return OVERVIEW_CACHE_DIR / f"{doc_hash}.json"


def _load_cached(doc_hash: str) -> dict | None:
    p = _cache_path(doc_hash)
    if p.exists():
        try:
            with open(p, "r", encoding="utf-8") as f:
                cached = json.load(f)
        except Exception:
            return None
        if not isinstance(cached, dict) or cached.get("schema_version") != OVERVIEW_SCHEMA_VERSION:
            logger.info("Ignoring overview cache for hash %s: outdated schema", doc_hash[:8])
            return None
        return cached
    return None


def _save_cache(doc_hash: str, overview: dict) -> None:
    p = _cache_path(doc_hash)
    try:
        with open(p, "w", encoding="utf-8") as f:
            json.dump(overview, f, ensure_ascii=False, indent=2)
    except Exception as exc:
        logger.warning("Failed to save overview cache for hash %s: %s", doc_hash, exc)


