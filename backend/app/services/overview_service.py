def generate_document_overview(
    document_name: str,
    llm_fn,  # callable(prompt: str, temperature: float) -> str
    retriever,  # HybridSearch instance
) -> dict[str, Any]:
    """
    Generate (or load from cache) the full document overview.

    Args:
        document_name: filename (e.g. sample_ieee.pdf)
        llm_fn:        LLM callable (prompt, temperature) -> str
        retriever:     HybridSearch instance for passage retrieval

    Returns:
        dict with all overview fields and a per-section `section_status`;
        from cache if already generated.
    """
    from app.services.document_service import load_document_json
    from app.rag.scoring import calculate_document_iq
    from app.services.document_service import build_document_metadata

    safe_name = Path(document_name).name
    stem = Path(safe_name).stem

    try:
        doc_json = load_document_json(safe_name)
    except FileNotFoundError:
        raise ValueError(f"Document '{safe_name}' not found in JSON store.")

    doc_hash = doc_json.get("document_hash", "")

    # Check cache first (keyed on doc_hash; entries from older schema versions are ignored)
    if doc_hash:
        cached = _load_cached(doc_hash)
        if cached is not None:
            logger.info("Overview cache hit for %s (hash=%s)", safe_name, doc_hash[:8])
            return cached

    logger.info("Generating overview for %s (hash=%s)…", safe_name, doc_hash[:8] if doc_hash else "?")
    start = time.perf_counter()

    sections: dict[str, dict[str, Any]] = {}

    pages_list = doc_json.get("pages", [])
    full_text = " ".join(
        p.get("text", "") for p in pages_list if p.get("text", "").strip()
    )
    page_count = doc_json.get("total_pages", len(pages_list) or 1)
    language = _detect_language(full_text)

    # Figures / tables (isolated: a failure here must not break the overview)
    figures: list[dict[str, Any]] = []
    tables: list[dict[str, Any]] = []
    try:
        figures, tables = _extract_figures_tables(pages_list)
        if figures or tables:
            sections["figures_tables"] = _section("ok", None, method="caption_lines")
        else:
            sections["figures_tables"] = _section(
                "empty", None, method="caption_lines",
                note="No caption lines such as 'Figure N:' or 'Table N:' were found in the extracted text.",
            )
    except Exception as exc:
        logger.warning("Figure/table detection failed: %s", exc)
        sections["figures_tables"] = _section("failed", _err(exc))

    # Authors / year from doc JSON
    authors: list[str] = doc_json.get("authors", []) or []
    if isinstance(authors, str):
        authors = [a.strip() for a in authors.split(",") if a.strip()]

    year = doc_json.get("year") or doc_json.get("publication_year")
    if year:
        try:
            year = int(str(year)[:4])
        except (ValueError, TypeError):
            year = None

    # Metadata disclosure: say what is missing instead of silently inventing it
    doc_title = doc_json.get("title")
    title_source = "document" if doc_title else "filename"
    missing: list[str] = []
    if not doc_title:
        missing.append("title")
    if not authors:
        missing.append("authors")
    if not year:
        missing.append("year")
    sections["metadata"] = _section(
        "partial" if missing else "ok", None, missing=missing, title_source=title_source,
    )

    # Key topics
    key_topics: list[str] = doc_json.get("key_topics", []) or doc_json.get("topics", []) or []
    key_topics_basis = "document_metadata"
    if not key_topics and full_text:
        key_topics_basis = "frequency_heuristic"
        words = re.findall(r"\b[A-Z][a-z]{3,}\b", full_text)
        freq: dict[str, int] = {}
        for w in words:
            freq[w] = freq.get(w, 0) + 1
        key_topics = [w for w, _ in sorted(freq.items(), key=lambda x: -x[1])[:10]]
    if not key_topics:
        sections["key_topics"] = _section("empty", None, basis=None)
    elif key_topics_basis == "document_metadata":
        sections["key_topics"] = _section("ok", None, basis=key_topics_basis)
    else:
        sections["key_topics"] = _section(
            "partial", None, basis=key_topics_basis,
            note="Most frequent capitalised words in the text, not extracted topics.",
        )

    # Document IQ
    try:
        metadata = build_document_metadata(safe_name)
        iq_report = calculate_document_iq(metadata)
        sections["document_iq"] = _section("ok")
    except Exception as exc:
        logger.warning("IQ calculation failed: %s", exc)
        iq_report = {}
        sections["document_iq"] = _section("failed", _err(exc))

    # Retrieval
    passages: list[dict] = []
    try:
        passages = retriever.search(
            f"What are the main findings, methods and contributions of {stem}?",
            top_k=12,
            document_names=[safe_name],
        ) or []
        if passages:
            sections["retrieval"] = _section("ok", None, passages=len(passages))
        else:
            sections["retrieval"] = _section("empty", None, passages=0)
    except Exception as exc:
        logger.warning("Passage retrieval failed for overview: %s", exc)
        passages = []
        sections["retrieval"] = _section("failed", _err(exc))

    # Summary and questions (each reports its own status)
    summary_status: dict[str, Any] = {}
    summary_sentences = _generate_summary(llm_fn, safe_name, passages, summary_status)
    if summary_status.get("status") == "unavailable" and sections["retrieval"]["status"] == "failed":
        summary_status["error"] = "Retrieval failed: " + (sections["retrieval"]["error"] or "unknown error")
    sections["summary"] = summary_status

    question_status: dict[str, Any] = {}
    question_details = _generate_suggested_question_details(llm_fn, stem, passages, question_status)
    sections["suggested_questions"] = question_status

    elapsed = round((time.perf_counter() - start) * 1000, 1)
    logger.info("Overview generated for %s in %.0f ms", safe_name, elapsed)

    overview: dict[str, Any] = {
        "schema_version": OVERVIEW_SCHEMA_VERSION,
        "document_name": safe_name,
        "document_hash": doc_hash,
        "title": doc_title or stem,
        "authors": authors,
        "year": year,
        "page_count": page_count,
        "language": language,
        "figure_count": len(figures),
        "table_count": len(tables),
        "figures": figures,
        "tables": tables,
        "summary_sentences": summary_sentences,
        "key_topics": key_topics,
        "document_iq": iq_report,
        "suggested_questions": [d["text"] for d in question_details],
        "question_details": question_details,
        "section_status": sections,
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "generation_ms": elapsed,
        "from_cache": False,
    }

    # Persist to cache by document hash, unless an infrastructure section failed
    # (retrying on the next request is better than freezing a transient failure).
    failed_infra = [n for n in _NON_CACHEABLE_FAILURES if sections.get(n, {}).get("status") == "failed"]
    if doc_hash and not failed_infra:
        _save_cache(doc_hash, {**overview, "from_cache": True})
    elif failed_infra:
        logger.info("Overview for %s not cached; failed sections: %s", safe_name, ", ".join(failed_infra))

    return overview