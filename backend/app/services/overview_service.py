# Language detection (pure-Python, no model)
# ---------------------------------------------------------------------------

_LANG_MARKERS = {
    "en": {"the", "of", "and", "in", "is", "to", "a", "that", "for", "with"},
    "fr": {"le", "de", "et", "en", "que", "une", "la", "les", "des", "pour"},
    "de": {"die", "der", "und", "in", "ist", "von", "das", "mit", "ein", "nicht"},
    "es": {"de", "la", "el", "en", "y", "que", "los", "una", "por", "para"},
    "zh": set(),
}


def _detect_language(text: str) -> str:
    sample = text[:2000].lower()
    if re.search(r"[一-鿿]", sample):
        return "zh"
    words = set(re.findall(r"\b[a-z]{2,}\b", sample))
    scores = {lang: len(words & markers) for lang, markers in _LANG_MARKERS.items() if markers}
    if not scores:
        return "en"
    return max(scores, key=scores.get)  # type: ignore[arg-type]


# ---------------------------------------------------------------------------
# Figure / table detection (caption-based, no fabricated entries)
# ---------------------------------------------------------------------------

def _make_svg_thumbnail(label: str, kind: str = "figure") -> str:
    """Generic placeholder icon. It is NOT an image of the real figure/table."""
    color = "%23d2434e" if kind == "figure" else "%23a7d0d2"
    encoded_label = urllib.parse.quote(label)
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="160" height="100" viewBox="0 0 160 100">'
        f'<rect width="160" height="100" fill="%23141d26" rx="8" stroke="{color}" stroke-width="1.5"/>'
        f'<path d="M20 70 L50 40 L80 65 L110 30 L140 70" fill="none" stroke="{color}" stroke-width="2" stroke-linecap="round"/>'
        f'<circle cx="110" cy="30" r="3" fill="{color}"/>'
        f'<text x="80" y="88" fill="%23f3faf0" font-family="sans-serif" font-size="10" font-weight="bold" text-anchor="middle">{encoded_label}</text>'
        f'</svg>'
    )
    return f"data:image/svg+xml;utf8,{svg}"


# A caption is a line that STARTS with "Figure 3:" / "Fig. 3." / "Table 2 -" followed by text.
# In-text mentions such as "see Figure 3" do not match and are therefore not counted.
_CAPTION_RE = re.compile(
    r"^[ \t]*(?P<kind>fig(?:ure)?|table)\.?[ \t]*(?P<num>\d+)[ \t]*[.:\-–—][ \t]*(?P<caption>\S[^\n]*)$",
    re.IGNORECASE | re.MULTILINE,
)


def _page_number(page: dict[str, Any], position: int) -> int:
    """Page number from the page's own metadata; falls back to its 1-based order in the pages array."""
    for key in ("page", "page_number", "page_num"):
        value = page.get(key)
        if isinstance(value, int) and value >= 1:
            return value
        if isinstance(value, str) and value.strip().isdigit():
            return int(value.strip())
    return position + 1


def _extract_figures_tables(
    pages: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """
    Detect figures/tables from real caption lines in each page's text.

    Returns (figures, tables). A document without captions yields two empty lists.
    The first caption found for a given number wins (later duplicates are ignored).
    """
    found: dict[str, dict[int, dict[str, Any]]] = {"figure": {}, "table": {}}

    for position, page in enumerate(pages or []):
        text = page.get("text", "") or ""
        if not text.strip():
            continue
        page_no = _page_number(page, position)
        for m in _CAPTION_RE.finditer(text):
            kind = "table" if m.group("kind").lower() == "table" else "figure"
            num = int(m.group("num"))
            if num in found[kind]:
                continue
            found[kind][num] = {
                "num": num,
                "caption": m.group("caption").strip()[:300],
                "page": page_no,
            }

    figures = [
        {
            "id": f"fig_{num}",
            "label": f"Figure {num}",
            "caption": item["caption"],
            "page": item["page"],
            "thumbnail": _make_svg_thumbnail(f"Figure {num}", kind="figure"),
            "thumbnail_is_placeholder": True,
        }
        for num, item in sorted(found["figure"].items())
    ]
    tables = [
        {
            "id": f"tbl_{num}",
            "label": f"Table {num}",
            "caption": item["caption"],
            "page": item["page"],
            "thumbnail": _make_svg_thumbnail(f"Table {num}", kind="table"),
            "thumbnail_is_placeholder": True,
        }
        for num, item in sorted(found["table"].items())
    ]
    return figures, tables


# ---------------------------------------------------------------------------
# Suggested questions (5 questions, each labelled grounded or exploratory)
# ---------------------------------------------------------------------------

_QUESTIONS_INSTRUCTIONS = """\
You are an academic research assistant.
Given the RETRIEVED PASSAGES from a document, generate exactly 5 insightful
research questions a reader would want answered after reading this document.
Return ONLY a JSON array of 5 strings, no commentary, no markdown.

Example: ["What is ...", "How does ...", "Why does ...", "What are ...", "Can ..."]
"""


def _generate_suggested_question_details(
    llm_fn,
    stem: str,
    passages: list[dict],
    status: dict[str, Any] | None = None,
) -> list[dict[str, str]]:
    """
    Return exactly 5 questions as {"text", "type"}.

      type = "grounded"    -> generated by the LLM from retrieved document passages
                              (derived from the document; not verified as answerable)
      type = "exploratory" -> generic template, NOT derived from this document's content

    If `status` is given it is filled with the section status for the questions.
    """
    grounded: list[str] = []
    error: str | None = None

    if passages:
        passage_blocks = []
        for idx, p in enumerate(passages[:10], start=1):
            text = p.get("text", "").strip()[:600]
            doc = p.get("document", "")
            page = p.get("page", "N/A")
            passage_blocks.append(f"[Passage {idx}] page={page} doc={doc}\n{text}")

        prompt = (
            _QUESTIONS_INSTRUCTIONS
            + "\n\n=== RETRIEVED PASSAGES ===\n\n"
            + "\n\n---\n\n".join(passage_blocks)
            + "\n\n=== JSON QUESTIONS ARRAY ==="
        )

        try:
            raw = llm_fn(prompt, temperature=0.3)
            cleaned = raw.strip()
            cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned, flags=re.IGNORECASE)
            cleaned = re.sub(r"\s*```$", "", cleaned).strip()
            parsed = json.loads(cleaned)
            if not isinstance(parsed, list):
                raise ValueError("LLM did not return a JSON array")
            grounded = [str(q).strip() for q in parsed if q and str(q).strip()][:5]
            if not grounded:
                raise ValueError("LLM returned no questions")
        except Exception as exc:
            error = _err(exc)
            grounded = []
            logger.warning("Failed to generate suggested questions via LLM: %s", exc)

    details: list[dict[str, str]] = [{"text": q, "type": "grounded"} for q in grounded]

    # Generic templates, always labelled exploratory.
    fallbacks = [
        f"What are the central research objectives and methodologies investigated in {stem}?",
        f"What empirical benchmarks and performance metrics does {stem} achieve?",
        f"How does the proposed framework differ from existing baseline approaches?",
        f"What are the core technical limitations and experimental constraints described?",
        f"What future research directions and system optimizations are suggested by the authors?",
    ]
    seen = {d["text"].casefold() for d in details}
    for fb in fallbacks:
        if len(details) >= 5:
            break
        if fb.casefold() not in seen:
            seen.add(fb.casefold())
            details.append({"text": fb, "type": "exploratory"})
    details = details[:5]

    if status is not None:
        g = sum(1 for d in details if d["type"] == "grounded")
        e = len(details) - g
        if not passages:
            status.update(_section(
                "unavailable",
                "No document passages were retrieved, so no document-grounded questions could be generated.",
                grounded=g, exploratory=e,
            ))
        elif error:
            status.update(_section("failed", error, grounded=g, exploratory=e))
        elif e > 0:
            status.update(_section("partial", None, grounded=g, exploratory=e))
        else:
            status.update(_section("ok", None, grounded=g, exploratory=e))

    return details


def _generate_suggested_questions(llm_fn, stem: str, passages: list[dict]) -> list[str]:
    """Plain-text view of the suggested questions (kept for backward compatibility)."""
    return [d["text"] for d in _generate_suggested_question_details(llm_fn, stem, passages)]


# ---------------------------------------------------------------------------
# Summary generation via grounded_generate path (up to 5 sentences with page refs)
# ---------------------------------------------------------------------------

def _passage_page(passage: dict) -> str | None:
    """Return the passage's real page as a string, or None if the passage has no usable page."""
    pg = passage.get("page")
    if pg is None:
        return None
    pg_str = str(pg).strip()
    if not pg_str or pg_str.upper() == "N/A":
        return None
    return pg_str


def _generate_summary(
    llm_fn,
    doc_name: str,
    passages: list[dict],
    status: dict[str, Any] | None = None,
) -> list[dict[str, Any]]:
    """
    Generate a grounded summary of up to 5 sentences.

    Each returned sentence has a quote taken verbatim from a retrieved passage and a page
    reference taken from that passage's own page metadata. A sentence whose passages carry
    no real page is dropped rather than given an invented reference.

    Returns list of dicts: {text, source_ids, quote, page_ref, support}
      support = "grounded"   -> LLM sentence verified against its cited passage
      support = "extractive" -> verbatim sentence copied from a retrieved passage

    If `status` is given it is filled with the section status for the summary.
    """
    if not passages:
        if status is not None:
            status.update(_section("unavailable", "No document passages were retrieved."))
        return []

    query = (
        f"Write a comprehensive 5-sentence academic summary of the document '{doc_name}'. "
        "Every sentence must be grounded with an exact verbatim quote from a cited passage."
    )

    prompt = build_grounded_prompt(query, passages)
    verified = []
    llm_error: str | None = None
    if prompt:
        try:
            raw = llm_fn(prompt, temperature=0.0)
            verified = verify_and_filter_sentences(raw, passages)
        except Exception as exc:
            llm_error = _err(exc)
            logger.warning("Grounded summary generation warning: %s", exc)

    enriched: list[dict[str, Any]] = []
    used_quotes: set[str] = set()

    for sent in verified:
        if len(enriched) >= 5:
            break
        pages: list[str] = []
        for sid in sent.get("source_ids", []):
            try:
                idx = int(sid) - 1
            except (ValueError, TypeError):
                continue
            if 0 <= idx < len(passages):
                pg = _passage_page(passages[idx])
                if pg is not None:
                    pages.append(pg)
        if not pages:
            # No resolvable real page: do not invent one.
            continue
        quote_str = sent.get("quote", "").strip()
        used_quotes.add(quote_str.casefold())
        enriched.append({
            "text": sent["text"],
            "source_ids": sent["source_ids"],
            "quote": quote_str,
            "page_ref": f"Page {', '.join(sorted(set(pages)))}",
            "support": "grounded",
        })

    # Top up with verbatim sentences from retrieved passages (only passages with a real page).
    if len(enriched) < 5:
        for idx, p in enumerate(passages):
            if len(enriched) >= 5:
                break
            pg = _passage_page(p)
            if pg is None:
                continue
            p_text = p.get("text", "").strip()
            p_sents = [s.strip() for s in re.split(r"(?<=[.!?])\s+", p_text) if len(s.strip()) > 35]
            for s in p_sents:
                if len(enriched) >= 5:
                    break
                if s.casefold() not in used_quotes:
                    used_quotes.add(s.casefold())
                    enriched.append({
                        "text": s,
                        "source_ids": [idx + 1],
                        "quote": s,
                        "page_ref": f"Page {pg}",
                        "support": "extractive",
                    })

    result = enriched[:5]

    if status is not None:
        g = sum(1 for s in result if s["support"] == "grounded")
        e = len(result) - g
        if not result:
            status.update(_section("failed" if llm_error else "empty", llm_error, grounded=0, extractive=0))
        elif llm_error:
            status.update(_section("partial", llm_error, grounded=g, extractive=e))
        elif e == 0:
            status.update(_section("ok", None, grounded=g, extractive=e))
        else:
            status.update(_section("partial", None, grounded=g, extractive=e))

    return result


